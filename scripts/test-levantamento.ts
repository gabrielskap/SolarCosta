import assert from 'node:assert/strict';
import { areaPoligono, areaSuperficie, cabe, distribuir, escalaSatelite, poligonoValido, sobrepoe, type LevantamentoTelhado } from '../src/utils/levantamentoTelhado.ts';
import {posicaoSolar,incidenciaDireta} from '../src/utils/posicaoSolar.ts';
import {aproximarCamera,limitarCamera} from '../src/utils/cameraTelhado.ts';
import { dimensionar } from '../src/utils/solar.ts';
import { levantamentoTelhadoSchema } from '../server/src/schemas/levantamentoTelhado.ts';
const ret=(x:number,y:number,w:number,h:number)=>[{x,y},{x:x+w,y},{x:x+w,y:y+h},{x,y:y+h}];
const aguaId=crypto.randomUUID();
const l:LevantamentoTelhado={versao:1,origem:'manual',larguraM:20,alturaM:20,norte:0,tipologia:'Plano',escalaConfirmada:true,aguas:[{id:aguaId,nome:'Principal',pontos:ret(0,0,10,10),inclinacao:0,azimute:0}],obstaculos:[],modulo:{modelo:'Teste',larguraM:1,alturaM:2,potenciaWp:500},espacamentoM:0.1,recuoM:0.3,placas:[]};
assert.equal(areaPoligono(ret(0,0,10,10)),100);
assert.equal(poligonoValido([{x:0,y:0},{x:5,y:5},{x:0,y:5},{x:5,y:0}]),false);
assert.equal(cabe(ret(0.1,1,1,2),l.aguas[0].pontos,[],0.3),false,'recuo protege borda');
assert.equal(cabe(ret(1,1,2,2),l.aguas[0].pontos,[ret(2,2,2,2)],0),false,'obstáculo excluído');
// Todos os vértices estão dentro, mas duas arestas atravessam o entalhe.
const u=[{x:0,y:0},{x:10,y:0},{x:10,y:10},{x:7,y:10},{x:7,y:3},{x:3,y:3},{x:3,y:10},{x:0,y:10}];
assert.equal(cabe(ret(1,1,8,4),u,[],0),false,'arestas não atravessam concavidades');
assert.equal(distribuir({...l,escalaConfirmada:false},20).length,0);
const placas=distribuir(l,20);
assert.equal(placas.length,20);
assert(placas.every(p=>cabe(p.pontos,l.aguas[0].pontos,[],l.recuoM)));
assert(!placas.some((a,i)=>placas.some((b,j)=>j>i&&sobrepoe(a.pontos,b.pontos))));
const inclinado={...l,aguas:[{...l.aguas[0],inclinacao:60}]};
assert(Math.abs(areaSuperficie(inclinado)-200)<1e-8);
const d=dimensionar({consumoKwh:1000,hsp:5,perdasPct:20,moduloWp:500,quantidadeInstalada:20,dimensoesModulo:l.modulo});
assert.equal(d.potenciaKwp,10);assert.equal(d.geracaoMediaKwh,1200);assert.equal(d.areaEstimadaM2,40);
const salvo={...l,placas};
assert(levantamentoTelhadoSchema.safeParse(JSON.parse(JSON.stringify(salvo))).success,'snapshot passa no contrato do servidor');
assert(!levantamentoTelhadoSchema.safeParse({...salvo,placas:[{...placas[0],aguaId:crypto.randomUUID()}]}).success);
assert(!levantamentoTelhadoSchema.safeParse({...salvo,imagem:'data:image/svg+xml;base64,PHN2Zz4='}).success);
assert(!levantamentoTelhadoSchema.safeParse({...salvo,escalaConfirmada:false}).success);
assert(!levantamentoTelhadoSchema.safeParse({...salvo,placas:[placas[0],placas[0]]}).success);
console.log('OK: área, concavidade, obstáculos, recuos, colisões, escala, inclinação, dimensionamento e contrato de persistência.');
const s20=escalaSatelite(-19.9,20),s19=escalaSatelite(-19.9,19);
assert(Math.abs(s19.larguraM-2*s20.larguraM)<1e-8,'zoom mantém escala física correta');
assert(Math.abs(escalaSatelite(0,20).larguraM-95.546285)<0.001);
const inverno=posicaoSolar('2026-06-21',12,-19.9,-43.9,-3);
assert(Math.abs(inverno.elevacao-46.66)<0.5,'altura solar ao meio-dia no inverno em BH');
assert(posicaoSolar('2026-06-21',0,-19.9,-43.9,-3).elevacao<0,'noite não recebe luz direta');
const am=posicaoSolar('2026-03-20',9,0,0,0),pm=posicaoSolar('2026-03-20',15,0,0,0);
assert(am.azimute>80&&am.azimute<100&&pm.azimute>260&&pm.azimute<280,'Sol nasce a leste e se põe a oeste no equinócio');
assert(incidenciaDireta(inverno.elevacao,inverno.azimute,30,0)>incidenciaDireta(inverno.elevacao,inverno.azimute,30,180));
assert.equal(incidenciaDireta(-10,0,0,0),0);
assert(levantamentoTelhadoSchema.safeParse({...salvo,satelite:{latitude:-19.9,longitude:-43.9,zoom:20,larguraPx:640,alturaPx:640},localizacao:{latitude:-19.9,longitude:-43.9},simulacao:{data:'2026-06-21',hora:12,fuso:-3,mostrarIncidencia:true,mostrarSombras:true}}).success);
console.log('OK: escala Web Mercator, posição solar, noite, orientação e persistência da simulação.');
const camera={zoom:1,centro:{x:50,y:40}};
const ampliada=aproximarCamera(camera,2,{x:60,y:30},100,80);
assert.equal(ampliada.zoom,2);
assert.deepEqual(ampliada.centro,{x:55,y:35});
assert.equal((60-camera.centro.x)/(100/camera.zoom),(60-ampliada.centro.x)/(100/ampliada.zoom),'âncora permanece no mesmo ponto da tela');
assert.deepEqual(aproximarCamera(ampliada,0.5,{x:60,y:30},100,80),camera);
assert.deepEqual(limitarCamera({zoom:4,centro:{x:-100,y:999}},100,80),{zoom:4,centro:{x:12.5,y:70}});
assert.equal(aproximarCamera(camera,100,camera.centro,100,80).zoom,12);
assert.equal(aproximarCamera(camera,0.1,camera.centro,100,80).zoom,1);
console.log('OK: zoom ancorado, retorno ao enquadramento e limites de navegação.');
