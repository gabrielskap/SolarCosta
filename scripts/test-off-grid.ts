import assert from 'node:assert/strict';
import { cargasOffGridPadrao, configOffGridPadrao, dimensionarSistema } from '../server/src/domain/offGrid';

const calcular = (config = {}, cargas = cargasOffGridPadrao()) => dimensionarSistema(cargas, {...configOffGridPadrao,...config});
const perto = (real:number, esperado:number) => assert.ok(Math.abs(real-esperado)<1e-9, `${real} != ${esperado}`);
const r=calcular();
perto(r.potenciaTotalW,1375);
perto(r.consumoDiarioKWh,6.24);
perto(r.consumoCorrigidoKWh,6.5);
perto(r.potenciaInversorRecomendadaW,1787.5);
perto(r.capacidadeMinimaAh,6500/(0.8*0.95*48));
perto(r.energiaMinimaBancoKWh,6500/(0.8*0.95)/1000);
perto(r.geracaoModuloKWh,2.0496);
assert.equal(r.quantidadeBaterias,2);
assert.equal(r.quantidadeModulos,4);
perto(r.potenciaSistemaKWp,2.44);
assert.equal(r.consultarFabricante,false);
const zero=calcular({},[]);
assert.equal(zero.quantidadeBaterias,1);
assert.equal(zero.quantidadeModulos,0);
const item=[{id:'1',nome:'Carga',potenciaW:1000,quantidade:1,horasDia:1}];
const limite={eficienciaInversor:100,profundidadeDescarga:100,eficienciaCarga:100,tensaoBateria:10,capacidadeBateriaAh:10};
assert.equal(calcular(limite,item).consultarFabricante,false);
assert.equal(calcular({...limite,capacidadeBateriaAh:9.99},item).consultarFabricante,true);
assert.equal(calcular({...limite,capacidadeBateriaAh:9.99},item).quantidadeBaterias,11);
for(const config of [{eficienciaInversor:0},{profundidadeDescarga:101},{eficienciaCarga:-1},{perdasSistema:100},{perdasSistema:-1},{irradiacaoSolar:0},{fatorDias:0},{tensaoBateria:NaN},{potenciaModuloWp:Infinity}]) assert.throws(()=>calcular(config));
for(const patch of [{quantidade:1.5},{quantidade:-1},{potenciaW:-1},{horasDia:25},{horasDia:-1},{horasDia:NaN}]) assert.throws(()=>calcular({},[{...item[0],...patch}]));
assert.equal(calcular({fatorDias:2}).geracaoModuloKWh,r.geracaoModuloKWh*2);
assert.equal(calcular({},[{...item[0],horasDia:24,quantidade:0}]).consumoDiarioKWh,0);
console.log('OFF-Grid: resultados da planilha, arredondamentos, limite Powersafe e validações passaram.');
